func main() {
	outPath := "sdk-go/sdkgo/types.go"
	if len(os.Args) > 1 {
		outPath = os.Args[1]
	}

	// Derive meta-repo root from the output file path.
	// Assumes types.go lives at <root>/sdk-go/sdkgo/types.go.
	absOut, err := filepath.Abs(outPath)
	if err != nil {
		fatalf("abs(%s): %v", outPath, err)
	}
	sdkgoDir := filepath.Dir(absOut)       // .../sdk-go/sdkgo/
	sdkDir := filepath.Dir(sdkgoDir)       // .../sdk-go/
	repoRoot := filepath.Dir(sdkDir)       // .../   (meta-repo root)
	schemasDir := filepath.Join(repoRoot, "schemas", "v0.3")

	// Validate that every referenced schema file exists and is valid JSON.
	for _, entry := range schemaEntries {
		schemaPath := filepath.Join(schemasDir, entry.filename+".schema.json")
		if err := validateSchema(schemaPath); err != nil {
			fatalf("schema %s: %v", schemaPath, err)
		}
	}

	// Generate source.
	raw := generateSource()

	// Canonicalize with gofmt for byte-identical output across runs.
	formatted, err := format.Source(raw)
	if err != nil {
		fatalf("go/format: %v\n--- unformatted source ---\n%s", err, raw)
	}

	// Write output.
	if err := os.WriteFile(absOut, formatted, 0o644); err != nil {
		fatalf("write %s: %v", absOut, err)
	}
	fmt.Fprintf(os.Stderr, "gen: wrote %s\n", absOut)
}

// validateSchema checks that the file at path exists and is parseable JSON.
func validateSchema(path string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var v interface{}
	return json.Unmarshal(data, &v)
}

// generateSource builds the raw (pre-gofmt) Go source for types.go.
func generateSource() []byte {
	var b bytes.Buffer

	b.WriteString(fileHeader)
	b.WriteByte('\n')

	for _, entry := range schemaEntries {
		for _, s := range entry.structs {
			// Doc comment.
			fmt.Fprintf(&b, "// %s\n", s.comment)
			// Struct declaration.
			fmt.Fprintf(&b, "type %s struct {\n", s.name)
			for _, f := range s.fields {
				fmt.Fprintf(&b, "\t%s %s `%s`\n", f.name, f.typ, f.jsonTag)
			}
			fmt.Fprintf(&b, "}\n\n")
		}
	}

	return b.Bytes()
}

func fatalf(format string, args ...interface{}) {
	fmt.Fprintf(os.Stderr, "gen: "+format+"\n", args...)
	os.Exit(1)
}
